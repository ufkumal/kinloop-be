-- ---------------------------------------------------------------------
-- 7) Dogrulama (beklenen degerler yorumda)
-- ---------------------------------------------------------------------
-- activities:            128
-- activity_instructions: 128
-- activity_steps:        522
-- activity_materials:    227
-- activity_outcomes:     385
DO $$
DECLARE c_act INT; c_ins INT; c_stp INT; c_mat INT; c_out INT;
BEGIN
    SELECT count(*) INTO c_act FROM activities WHERE scope = 'HOME';
    SELECT count(*) INTO c_ins FROM activity_instructions ai JOIN activities a ON a.id = ai.activity_id WHERE a.scope = 'HOME';
    SELECT count(*) INTO c_stp FROM activity_steps;
    SELECT count(*) INTO c_mat FROM activity_materials;
    SELECT count(*) INTO c_out FROM activity_outcomes;
    RAISE NOTICE 'activities=% instructions=% steps=% materials=% outcomes=%', c_act, c_ins, c_stp, c_mat, c_out;
    IF c_act < 128 THEN RAISE EXCEPTION 'Beklenen 128 aktivite yuklenmedi (bulunan: %)', c_act; END IF;
END $$;

